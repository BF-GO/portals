package net.thenextlvl.portals.particle;

/**
 * Defines how portal particles are distributed across a portal.
 *
 * @since 1.8.0
 */
public enum PortalParticlePattern {
    /**
     * Particles are distributed across the portal volume.
     *
     * @since 1.8.0
     */
    FILL,
    /**
     * Particles are distributed along the portal outline.
     *
     * @since 1.8.0
     */
    OUTLINE
}
